/**
 * `sdk/contract/sealed-vectors.json` — generated by the server's own crate —
 * and the four checks `sealed-transport.md` requires of every SDK.
 */
class SealedTransportTest {

    private val vectors: JsonObject = run {
        val dir = System.getProperty("trustsy.contractDir") ?: "../contract"
        WireJson.parseToJsonElement(File(dir, "sealed-vectors.json").readText()).jsonObject
    }
    /** One per suite: `x25519` then `xwing`. Every check below runs on each. */
    private class Suite(entry: JsonObject) {
        val kem = Sealed.Kem.of(entry["suite"]!!.jsonObject["kem_id"]!!.jsonPrimitive.content.toInt())!!
        val key = entry["key"]!!.jsonObject
        fun k(name: String) = key[name]!!.jsonPrimitive.content
        val cases = entry["cases"]!!.jsonArray.map { it.jsonObject }
    }
    private val suites = vectors["suites"]!!.jsonArray.map { Suite(it.jsonObject) }

    /** What Android seals with: the fake-gateway tests below run on it. */
    private val pq = suites.single { it.kem == Sealed.Kem.XWING }
    private fun JsonObject.s(name: String) = this[name]!!.jsonPrimitive.content

    private fun hex(s: String) = ByteArray(s.length / 2) { s.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
    private fun ByteArray.hex() = joinToString("") { "%02x".format(it) }
    private fun hpke(kem: Sealed.Kem) = HPKE(HPKE.mode_base, kem.bcId, HPKE.kdf_HKDF_SHA256, HPKE.aead_AES_GCM256)

    /** A library RECIPIENT, as the server is: returns plaintext and its export. */
    private fun openAsServer(suite: Suite, body: ByteArray, info: ByteArray): Pair<ByteArray, ByteArray> {
        val hpke = hpke(suite.kem)
        val keys = hpke.deserializePrivateKey(hex(suite.k("secret_key_hex")), hex(suite.k("public_key_hex")))
        val encEnd = Sealed.HEADER_LEN + suite.kem.encLen
        val ctx = hpke.setupBaseR(body.copyOfRange(Sealed.HEADER_LEN, encEnd), keys, info)
        val plain = ctx.open(ByteArray(0), body.copyOfRange(encEnd, body.size))
        return plain to ctx.export("trustsy sealed response v1".toByteArray(), 32)
    }

    @Test
    fun `the vectors carry both suites, X25519 then X-Wing`() {
        assertEquals(listOf(Sealed.Kem.X25519, Sealed.Kem.XWING), suites.map { it.kem })
    }

    // ---- the four contract checks, per suite --------------------------------------------

    @Test
    fun `1 - key config parses and info matches`() {
        for (suite in suites) {
            val config = Sealed.KeyConfig.parse(suite.k("key_config"))!!
            assertEquals(suite.k("key_id").toInt(), config.keyId)
            assertEquals(suite.kem, config.kem)
            assertEquals(suite.k("public_key_hex"), config.publicKey.hex())
            assertEquals(suite.k("request_info_hex"), config.info.hex())
        }
    }

    @Test
    fun `2 - a server-sealed request opens with a library recipient`() {
        for (suite in suites) {
            val info = hex(suite.k("request_info_hex"))
            for (c in suite.cases) {
                val label = "${suite.kem} ${c.s("name")}"
                val body = hex(c.s("request_body_hex"))
                val (plain, export) = openAsServer(suite, body, info)
                assertEquals(label, c.s("request_plaintext"), plain.toString(Charsets.UTF_8))
                assertEquals(label, c.s("export_secret_hex"), export.hex())
                assertEquals(label, c.s("enc_hex"), body.copyOfRange(Sealed.HEADER_LEN, Sealed.HEADER_LEN + suite.kem.encLen).hex())
            }
        }
    }

    @Test
    fun `3 - the vector responses open with the SDK's opener`() {
        for (suite in suites) {
            for (c in suite.cases) {
                val plain = Sealed.openResponse(hex(c.s("export_secret_hex")), hex(c.s("enc_hex")), hex(c.s("response_body_hex")))
                assertEquals("${suite.kem} ${c.s("name")}", c.s("response_plaintext"), plain.toString(Charsets.UTF_8))
            }
        }
    }

    @Test
    fun `4 - the SDK's sealer round-trips through a library recipient`() {
        for (suite in suites) {
            val config = Sealed.KeyConfig.parse(suite.k("key_config"))!!
            val message = """{"v":1,"ts":1,"method":"GET","path":"/api/v1/collection-flow","token":"t"}""".toByteArray()
            val sealed = Sealed.sealRequest(config, message)
            assertArrayEquals(config.header, sealed.body.copyOfRange(0, Sealed.HEADER_LEN))
            assertEquals(suite.kem.encLen, sealed.enc.size)
            assertArrayEquals(sealed.enc, sealed.body.copyOfRange(Sealed.HEADER_LEN, Sealed.HEADER_LEN + suite.kem.encLen))
            val (plain, export) = openAsServer(suite, sealed.body, config.info)
            assertArrayEquals(message, plain)
            assertArrayEquals(export, sealed.secret)
        }
    }

    // ---- key config and response integrity ----------------------------------------------

    @Test
    fun `the dev key config parses and malformed ones do not`() {
        assertNotNull(Sealed.KeyConfig.parse("AQAgAAEAAlftwPm3Tckm0oDXKB2LUpCcqfYNbSihX2L4bKTH6NB6"))
        assertNull(Sealed.KeyConfig.parse(""))
        assertNull(Sealed.KeyConfig.parse("AQAgAAEAAlftwPm3Tckm0oDXKB2LUpCcqfYNbSihX2L4bKTH6NB")) // 38.25 bytes
        assertNull(Sealed.KeyConfig.parse("AQAgAAEAAlftwPm3Tckm0oDXKB2LUpCcqfYNbSihX2L4bKTH6NB6AA")) // 40 bytes
        assertNull(Sealed.KeyConfig.parse("AQAgAAEAAlftwPm3Tckm0oDXKB2LUpCcqfYNbSihX2L4bKTH6NB+")) // not url-safe
        // Same length, AEAD id 0x0001 (AES-128-GCM): another suite is refused.
        assertNull(Sealed.KeyConfig.parse("AQAgAAEAAVftwPm3Tckm0oDXKB2LUpCcqfYNbSihX2L4bKTH6NB6"))
    }

    // ---- choosing among pinned keys --------------------------------------------------------

    private val classical get() = suites.single { it.kem == Sealed.Kem.X25519 }.k("key_config")
    private val postQuantum get() = pq.k("key_config")

    /** A key config with [kemId] in its header and [size] bytes in all. */
    private fun configWith(kemId: Int, size: Int): String {
        val raw = ByteArray(size).also {
            it[0] = 9; it[1] = (kemId shr 8).toByte(); it[2] = kemId.toByte(); it[4] = 1; it[6] = 2
        }
        return java.util.Base64.getUrlEncoder().withoutPadding().encodeToString(raw)
    }

    @Test
    fun `X-Wing is chosen whatever the order, X25519 alone still works`() {
        assertEquals(Sealed.Kem.XWING, Sealed.KeyConfig.select("$classical,$postQuantum")!!.kem)
        assertEquals(Sealed.Kem.XWING, Sealed.KeyConfig.select(" $postQuantum , $classical ")!!.kem)
        assertEquals(Sealed.Kem.X25519, Sealed.KeyConfig.select(classical)!!.kem)
        assertNull(Sealed.KeyConfig.select(""))
        assertNull(Sealed.KeyConfig.select(" , "))
    }

    @Test
    fun `a suite this SDK does not know is skipped`() {
        val future = configWith(0x0042, 7 + 1568) // ML-KEM-1024 alone
        assertEquals(Sealed.Kem.X25519, Sealed.KeyConfig.select("$future,$classical")!!.kem)
        assertNull(Sealed.KeyConfig.select(future))
    }

    @Test
    fun `a broken entry of a known suite refuses the whole pin, never downgrades`() {
        // A truncated X-Wing key beside a good X25519 one: falling back would
        // leave the app classical with nothing to say so.
        val truncated = postQuantum.dropLast(8)
        assertNull(Sealed.KeyConfig.select("$truncated,$classical"))
        assertNull(Sealed.KeyConfig.select("$classical,${configWith(0x647a, 7 + 1215)}"))
        assertNull(Sealed.KeyConfig.select("$classical,not+base64url"))
        assertNull(Sealed.KeyConfig.select("$classical,AQAg"))
    }

    @Test
    fun `within a suite the first pinned key wins`() {
        val other = configWith(0x647a, 7 + 1216).let { cfg ->
            // A well-formed X-Wing config under key id 9.
            Sealed.KeyConfig.parse(cfg)!!; cfg
        }
        assertEquals(pq.k("key_id").toInt(), Sealed.KeyConfig.select("$postQuantum,$other")!!.keyId)
        assertEquals(9, Sealed.KeyConfig.select("$other,$postQuantum")!!.keyId)
    }

    @Test
    fun `every seal uses a fresh enc`() {
        val config = Sealed.KeyConfig.parse(pq.k("key_config"))!!
        val a = Sealed.sealRequest(config, "x".toByteArray())
        val b = Sealed.sealRequest(config, "x".toByteArray())
        assertFalse(a.enc.contentEquals(b.enc))
    }

    @Test
    fun `a tampered response does not open`() {
        val c = pq.cases[0]
        val body = hex(c.s("response_body_hex"))
        body[body.size - 1] = (body[body.size - 1].toInt() xor 1).toByte()
        try {
            Sealed.openResponse(hex(c.s("export_secret_hex")), hex(c.s("enc_hex")), body)
            fail("opened a tampered response")
        } catch (_: Sealed.InvalidResponse) {
        }
        // Right bytes, wrong request: the secret of another request.
        try {
            Sealed.openResponse(hex(pq.cases[1].s("export_secret_hex")), hex(c.s("enc_hex")), hex(c.s("response_body_hex")))
            fail("opened with another request's secret")
        } catch (_: Sealed.InvalidResponse) {
        }
    }

    // ---- send() against a fake gateway --------------------------------------------------

    private val server = MockWebServer()
    private val requests = mutableListOf<RecordedRequest>()
    private val envelopes = mutableListOf<JsonObject>()
    private val encs = mutableListOf<String>()

    @After
    fun stop() = server.shutdown()

    /** Seal [plain] as the gateway does, with javax.crypto (independent of the SDK's opener). */
    private fun sealResponse(secret: ByteArray, enc: ByteArray, plain: String): ByteArray {
        val nonce = ByteArray(32).also { java.security.SecureRandom().nextBytes(it) }
        fun hmac(key: ByteArray, data: ByteArray) =
            Mac.getInstance("HmacSHA256").apply { init(SecretKeySpec(key, "HmacSHA256")) }.doFinal(data)
        val prk = hmac(enc + nonce, secret)
        val aesKey = hmac(prk, "key".toByteArray() + byteArrayOf(1))
        val iv = hmac(prk, "nonce".toByteArray() + byteArrayOf(1)).copyOf(12)
        val gcm = Cipher.getInstance("AES/GCM/NoPadding")
        gcm.init(Cipher.ENCRYPT_MODE, SecretKeySpec(aesKey, "AES"), GCMParameterSpec(128, iv))
        return nonce + gcm.doFinal(plain.toByteArray())
    }

    /** A gateway that answers each opened envelope with [answer]'s inner response. */
    private fun gateway(answer: (JsonObject) -> String?) {
        val info = hex(pq.k("request_info_hex"))
        server.dispatcher = object : Dispatcher() {
            override fun dispatch(request: RecordedRequest): MockResponse {
                requests += request
                val body = request.body.readByteArray()
                val enc = body.copyOfRange(Sealed.HEADER_LEN, Sealed.HEADER_LEN + pq.kem.encLen)
                encs += enc.hex()
                val (plain, secret) = openAsServer(pq, body, info)
                val envelope = WireJson.parseToJsonElement(plain.toString(Charsets.UTF_8)).jsonObject
                envelopes += envelope
                val inner = answer(envelope) ?: return MockResponse().setResponseCode(200)
                    .setHeader("Content-Type", "application/json").setBody("""{"status":200}""")
                return MockResponse().setResponseCode(200).setHeader("Content-Type", Sealed.CONTENT_TYPE)
                    .setBody(Buffer().write(sealResponse(secret, enc, inner)))
            }
        }
        server.start()
    }

    private val token = "00000000-0000-4000-8000-000000000001"

    private fun api(clock: () -> Long = { 1_791_830_000_000L }): ApiClient {
        val transport = SealedTransport(
            server.url("/").toString().trimEnd('/'),
            token,
            Sealed.KeyConfig.parse(pq.k("key_config"))!!,
            ApiClient.defaultHttp,
            clock,
        )
        return ApiClient(transport, telemetry = { null })
    }

    @Test
    fun `a push token is paired inside the envelope, and a refusal surfaces`() = runTest {
        var refuse = false
        gateway {
            if (refuse) """{"status":422,"content_type":"application/json","body":{"code":"invalid_push_token","message":"no"}}"""
            else """{"status":204}"""
        }
        api().registerPushToken("fcmToken:APA91bH-0123456789")
        val env = envelopes.single()
        assertEquals("POST", env["method"]!!.jsonPrimitive.content)
        assertEquals("/api/v1/collection-flow/push-token", env["path"]!!.jsonPrimitive.content)
        val body = env["body"]!!.jsonObject
        assertEquals("fcm", body["provider"]!!.jsonPrimitive.content)
        assertEquals("android", body["platform"]!!.jsonPrimitive.content)
        assertEquals("fcmToken:APA91bH-0123456789", body["token"]!!.jsonPrimitive.content)
        refuse = true
        val error = runCatching { api().registerPushToken("fcmToken:APA91bH-0123456789") }.exceptionOrNull()
        assertEquals(422, (error as com.trustsy.verify.internal.net.ApiException).status)
    }

    @Test
    fun `the request names the phone, in the shape the server reads`() = runTest {
        gateway { """{"status":200,"content_type":"application/json","body":{"id":"case","status":"active","state":"s"}}""" }
        val ua = SealedTransport.userAgent("SM-S918B", "15", "0.2.0")
        assertEquals("TrustsyVerify/0.2.0 (SM-S918B; Android 15)", ua)
        val transport = SealedTransport(
            server.url("/").toString().trimEnd('/'), token, Sealed.KeyConfig.parse(pq.k("key_config"))!!,
            ApiClient.defaultHttp, userAgent = ua,
        )
        ApiClient(transport, telemetry = { null }).snapshot()
        assertEquals(ua, requests.single().getHeader("User-Agent"))
        // `Build.MODEL` is the maker's free text: a `)` or `;` would end the model early.
        assertEquals("TrustsyVerify/0.2.0 (Foo Bar X; Android 15)", SealedTransport.userAgent("Foo (Bar; X)", "15", "0.2.0"))
    }

    @Test
    fun `calls go sealed to one endpoint with the token inside`() = runTest {
        gateway {
            """{"status":200,"content_type":"application/json","body":{"id":"case","status":"active","state":"s"}}"""
        }
        val snapshot = api().snapshot()
        assertEquals("case", snapshot.id)
        api().event("CONSENT_GIVEN", JsonObject(mapOf("geolocation" to JsonObject(emptyMap()))))

        assertEquals(listOf("/api/v1/sealed", "/api/v1/sealed"), requests.map { it.path })
        for (r in requests) {
            assertEquals("POST", r.method)
            assertEquals(Sealed.CONTENT_TYPE, r.getHeader("Content-Type")?.substringBefore(';'))
            assertNull("no Authorization header", r.getHeader("Authorization"))
            assertFalse("no token in the URL", token in r.requestUrl.toString())
        }
        assertEquals("GET", envelopes[0]["method"]!!.jsonPrimitive.content)
        assertEquals("/api/v1/collection-flow", envelopes[0]["path"]!!.jsonPrimitive.content)
        assertEquals(token, envelopes[0]["token"]!!.jsonPrimitive.content)
        assertEquals(1, envelopes[0]["v"]!!.jsonPrimitive.content.toInt())
        assertEquals(1_791_830_000_000L, envelopes[0]["ts"]!!.jsonPrimitive.long)
        assertNull("a GET carries no body", envelopes[0]["body"])
        assertEquals("/api/v1/collection-flow/events", envelopes[1]["path"]!!.jsonPrimitive.content)
        assertEquals(JsonPrimitive("CONSENT_GIVEN"), envelopes[1]["body"]!!.jsonObject["type"])
        assertEquals(setOf("v", "ts", "method", "path", "token", "body"), envelopes[1].keys)
    }

    @Test
    fun `an unsealed 200 is never believed`() = runTest {
        gateway { null }
        val e = runCatching { api().snapshot() }.exceptionOrNull()
        assertTrue("$e", e is SealedTransportException && e.resultCode == SealedTransport.SEALED_RESPONSE_INVALID)
    }

    @Test
    fun `inner statuses read like plain HTTP`() = runTest {
        gateway { """{"status":403,"content_type":"application/json","body":{"code":"vpn_not_allowed"}}""" }
        val e = runCatching { api().snapshot() }.exceptionOrNull()
        assertTrue("$e", e is ApiException && e.isAccessRefusal)
    }

    @Test
    fun `a stale clock is clock_skew`() = runTest {
        gateway { """{"status":400,"content_type":"application/json","body":{"code":"sealed_stale"}}""" }
        val e = runCatching { api().snapshot() }.exceptionOrNull()
        assertTrue("$e", e is SealedTransportException && e.resultCode == SealedTransport.CLOCK_SKEW)
    }

    @Test
    fun `a rotated key is sealing_key_rejected`() = runTest {
        server.enqueue(MockResponse().setResponseCode(422).setBody("""{"code":"sealed_unknown_key","message":"x"}"""))
        server.start()
        val e = runCatching { api().snapshot() }.exceptionOrNull()
        assertTrue("$e", e is SealedTransportException && e.resultCode == SealedTransport.SEALING_KEY_REJECTED)
        assertEquals(TrustsyResult.SEALING_KEY_REJECTED, SealedTransport.resultCodeOf(e as SealedTransportException))
    }

    @Test
    fun `a retry reseals rather than resending bytes`() = runTest {
        gateway { """{"status":200,"content_type":"application/json","body":{"id":"c","status":"active"}}""" }
        val client = api()
        repeat(3) { client.snapshot() }
        assertEquals(3, encs.size)
        assertEquals("a fresh enc per call", 3, encs.toSet().size)
    }
