/**
 * The face model and the dial-code registry are the web verify app's own files,
 * copied at build time so there is ONE copy of each in the repo. The model is
 * pinned by hash: the liveness thresholds on the server were set against these
 * exact weights (Google's `face_landmarker/float16/1`, Apache-2.0).
 */
abstract class SyncWebAssets : DefaultTask() {
    @get:InputFile abstract val model: RegularFileProperty
    @get:InputFile abstract val dialCodes: RegularFileProperty
    @get:Input abstract val modelSha256: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun sync() {
        val bytes = model.get().asFile.readBytes()
        val actual = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
        check(actual == modelSha256.get()) {
            "face_landmarker.task is $actual, expected ${modelSha256.get()} — the server's liveness " +
                "thresholds were set against the pinned model; re-check before changing it"
        }
        val out = outputDir.get().asFile.resolve("trustsy").apply { mkdirs() }
        out.resolve("face_landmarker.task").writeBytes(bytes)
        dialCodes.get().asFile.copyTo(out.resolve("dial_codes.json"), overwrite = true)
    }
}

val syncWebAssets = tasks.register<SyncWebAssets>("syncWebAssets") {
    model.set(file("../third_party/verify-web/public/models/face_landmarker.task"))
    dialCodes.set(file("../third_party/verify-web/src/flow/dialCodes.json"))
    modelSha256.set("64184e229b263107bc2b804c6625db1341ff2bb731874b0bcc2fe6544e0bc9ff")
    outputDir.set(layout.buildDirectory.dir("generated/trustsy-assets"))
}

androidComponents {
    onVariants { variant ->
        variant.sources.assets?.addGeneratedSourceDirectory(syncWebAssets, SyncWebAssets::outputDir)
    }
}

// Two destinations, one publication (com.trustsy:trustsy-verify):
// - `publishReleasePublicationToTrustsyRepository` writes a self-contained
//   Maven repository (default sdk/android/build/repository, or
//   -PtrustsyRepositoryDir=…) to host as static files; apps and the Flutter
//   plugin point a `maven { url }` at it. ci/consumer builds against it.
// - `publishToMavenLocal` for wrappers built on this machine.
publishing {
    publications {
        register<MavenPublication>("release") {
            groupId = "com.trustsy"
            artifactId = "trustsy-verify"
            version = sdkVersion
            afterEvaluate { from(components["release"]) }
            pom {
                name.set("trustsy Verify")
                description.set(
                    "Native Compose screens for trustsy verification flows, end-to-end sealed, " +
                        "with ICAO 9303 NFC chip reading.",
                )
                url.set("https://trustsy.com")
                licenses {
                    license {
                        name.set("Proprietary")
                        distribution.set("repo")
                    }
                }
                organization {
                    name.set("trustsy")
                    url.set("https://trustsy.com")
                }
            }
        }
    }
    repositories {
        maven {
            name = "trustsy"
            url = uri(
                providers.gradleProperty("trustsyRepositoryDir")
                    .map { rootProject.file(it) }
                    .getOrElse(rootProject.layout.buildDirectory.dir("repository").get().asFile),
            )
        }
    }
}

